#!/usr/bin/env python3
"""tools/port_ld.py -- bet 1.6a: the linker script of the REAL link (`make port-link`).

devkitARM links a 3dsx through `-specs=3dsx.specs`, whose `*link:` adds `-T 3dsx.ld`. tools/overlay_map.py's fragment (port/hwgen/overlay_map.ld)
was written for the trial link as `ld -T overlay_map.ld` + INSERT; with a real main script that fails ("`.data` not found for insert": ld applies INSERT
only to the built-in default script). So the real link uses a GENERATED FULL SCRIPT instead:

  port/hwgen/3dsx_port.ld     devkitARM's 3dsx.ld (read from $DEVKITARM at generation time) with the overlay map spliced in at three points:
                                - the linker-supplied symbols (SDK_OVERLAY_*_ID, arena/binary symbols) before SECTIONS;
                                - the `.ovl<N>.data/.sinit` + `.main.*` sections immediately BEFORE `.data` (they must precede it: the first
                                  statement that matches an input section wins), each assigned to the `data` PT_LOAD (the INSERT form inherited
                                  `rodata`, i.e. read-only memory);
                                - the `.ovl<N>.bss` + `.main.bss` sections after `__bss_start__ = .;` and before `.bss` (NOBITS, `data` PT_LOAD);
                                - `.ovl_pristine` (NOLOAD) after `.bss` and before `__bss_end__ = .;`.
  port/hwgen/3dsx_port.specs  devkitARM's 3dsx.specs with `-T <that script>`.

The restore audit (tools/port_link.py) asserts the resulting order: __bss_start__ <= .main.bss < .bss, __ovl_pristine_end <= __bss_end__.
usage: port_ld.py        (needs `make port-overlay-map` first)
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GEN = os.path.join(ROOT, "port/hwgen")


def main():
    dkp = os.environ.get("DEVKITPRO", "/opt/devkitpro")
    arm = os.environ.get("DEVKITARM", dkp + "/devkitARM")
    lib = os.path.join(arm, "arm-none-eabi/lib")
    base = open(os.path.join(lib, "3dsx.ld")).read()
    frag = open(os.path.join(GEN, "overlay_map.ld")).read()
    # the fragment: [symbols][SECTIONS{data}]INSERT BEFORE .data; [SECTIONS{bss}]INSERT BEFORE .bss; [SECTIONS{pristine}]INSERT AFTER .bss;
    parts = re.split(r"\nINSERT (?:BEFORE|AFTER) \.(?:data|bss);\n", frag)
    if len(parts) != 4:
        sys.exit("port_ld: unexpected overlay_map.ld shape (%d parts)" % len(parts))
    head_and_data, bss, pristine = parts[0], parts[1], parts[2]
    i = head_and_data.index("\nSECTIONS\n{")
    symbols, data = head_and_data[:i], head_and_data[i:]

    def body(block):
        m = re.search(r"SECTIONS\n\{\n(.*)\n\}\s*$", block, re.S)
        if not m:
            sys.exit("port_ld: no SECTIONS body")
        # each output section statement ends with a lone `    }` at 4-space indent: give it the data PT_LOAD
        return re.sub(r"^    \}$", "    } :data", m.group(1), flags=re.M)

    out = base
    marker = "\tSECTIONS\n" if False else None
    # symbols before SECTIONS
    out, n = re.subn(r"\nSECTIONS\n\{", "\n" + symbols.strip("\n").replace("\\", "\\\\") + "\n\nSECTIONS\n{", out, count=1)
    assert n == 1
    m = re.search(r"\n\t\.data :\n", out)
    assert m
    out = out[:m.start()] + "\n\t/* ---- overlay map (tools/port_ld.py from port/hwgen/overlay_map.ld) ---- */\n" + body(data) + "\n" + out[m.start():]
    m = re.search(r"\t__bss_start__ = \.;\n", out)
    assert m
    out = out[:m.end()] + body(bss) + "\n" + out[m.end():]
    m = re.search(r"\t__bss_end__ = \.;\n", out)
    assert m
    out = out[:m.start()] + body(pristine) + "\n" + out[m.start():]
    hdr = "/* GENERATED by tools/port_ld.py from devkitARM 3dsx.ld + port/hwgen/overlay_map.ld -- do not edit. */\n"
    open(os.path.join(GEN, "3dsx_port.ld"), "w").write(hdr + out)
    spec = open(os.path.join(lib, "3dsx.specs")).read()
    spec = spec.replace("-T 3dsx.ld%s", "-T " + os.path.join(GEN, "3dsx_port.ld"))
    open(os.path.join(GEN, "3dsx_port.specs"), "w").write(spec)
    print("port_ld: wrote port/hwgen/3dsx_port.ld (%d lines) and 3dsx_port.specs" % out.count("\n"))


if __name__ == "__main__":
    main()
