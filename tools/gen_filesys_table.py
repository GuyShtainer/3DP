"""Generate the ROM-check table (setup_fs_table / setup_fs_count) from the user's own pret checkout.

Joins platinum.us/filesys.sha1 (build path -> SHA-1) with platinum.us/filesys.csv (build path -> ROM path) and writes a C
source file. The output is a build artifact (build/generated-setup/), never committed. Run with `python3 -I`.

  gen_filesys_table.py --ref ../pokeplatinum --out build/generated-setup/setup_fs_table.c

Refuses (exit 1) on a missing file, a malformed line, a duplicate, or a path present in one list and not the other.
"""
import argparse
import re
import sys
from pathlib import Path

SHA1_LINE = re.compile(r"^([0-9a-f]{40}) \*(\S.*)$")
ROM_PATH = re.compile(r"^/[A-Za-z0-9_./+-]+$")


class TableError(Exception):
    """The reference files are missing, malformed or disagree with each other."""


def read_lines(path: Path) -> list[str]:
    """Return the file's lines, or raise TableError when it cannot be read."""
    try:
        return path.read_text(encoding="utf-8").splitlines()
    except (OSError, UnicodeDecodeError) as err:
        raise TableError(f"{path}: {err}") from err


def parse_sha1(path: Path) -> dict[str, str]:
    """Map build path -> lowercase hex SHA-1 from filesys.sha1."""
    out: dict[str, str] = {}
    for num, line in enumerate(read_lines(path), 1):
        match = SHA1_LINE.match(line)
        if not match:
            raise TableError(f"{path}:{num}: malformed line")
        if match.group(2) in out:
            raise TableError(f"{path}:{num}: duplicate path {match.group(2)}")
        out[match.group(2)] = match.group(1)
    return out


def parse_csv(path: Path) -> dict[str, str]:
    """Map build path -> ROM path from filesys.csv (header line, then 'source,target')."""
    lines = read_lines(path)
    if not lines or lines[0] != "Source File,Target File":
        raise TableError(f"{path}:1: unexpected header")
    out: dict[str, str] = {}
    for num, line in enumerate(lines[1:], 2):
        parts = line.split(",")
        if len(parts) != 2 or not parts[0] or not ROM_PATH.match(parts[1]):
            raise TableError(f"{path}:{num}: malformed line")
        if parts[0] in out:
            raise TableError(f"{path}:{num}: duplicate path {parts[0]}")
        out[parts[0]] = parts[1]
    return out


def build_table(sha1: dict[str, str], csv: dict[str, str]) -> list[tuple[str, str]]:
    """Join the two maps into (rom_path, sha1) pairs sorted by ROM path; refuse any mismatch."""
    only_sha, only_csv = sorted(set(sha1) - set(csv)), sorted(set(csv) - set(sha1))
    if only_sha or only_csv:
        raise TableError(f"path lists disagree: {len(only_sha)} only in filesys.sha1, {len(only_csv)} only in filesys.csv")
    rows = sorted((csv[path], sha1[path]) for path in sha1)
    if len({rom for rom, _ in rows}) != len(rows):
        raise TableError("two build paths map to one ROM path")
    return rows


def render(rows: list[tuple[str, str]]) -> str:
    """Return the C source text for the table."""
    lines = ['/* Generated by tools/gen_filesys_table.py from the local pret checkout. Not committed. */',
             '#include "hw_setup_core.h"', "const setup_fs_entry setup_fs_table[] = {"]
    for rom, digest in rows:
        octets = ", ".join(f"0x{digest[i:i + 2]}" for i in range(0, 40, 2))
        lines.append(f'    {{ "{rom}", {{ {octets} }} }},')
    lines += ["};", f"const uint32_t setup_fs_count = {len(rows)};", ""]
    return "\n".join(lines)


def main() -> int:
    """Command line entry; returns the process exit status."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--ref", required=True, type=Path, help="pret pokeplatinum checkout")
    parser.add_argument("--out", required=True, type=Path, help="C file to write")
    args = parser.parse_args()
    try:
        rows = build_table(parse_sha1(args.ref / "platinum.us" / "filesys.sha1"),
                           parse_csv(args.ref / "platinum.us" / "filesys.csv"))
    except TableError as err:
        print(f"gen_filesys_table: REFUSED: {err}", file=sys.stderr)
        return 1
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(rows), encoding="utf-8")
    print(f"gen_filesys_table: {len(rows)} entries -> {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
